function idadeEpeso(idade, peso) {
    //a função recebe dois parametros: idade e peso
    //o paremetro 'idade' guarda informações referente a idade
    //o parametro 'peso' guarda informações referebte ao peso
    
    return 'Idade: ' + idade + ' anos | Peso: ' + peso + ' kg';
    //junta os dois valores e retorna para o terminal
}
//o 'console.log' imprime o resultado da função (idade e peso)
console.log(idadeEpeso(17, 69)); //teste 1
console.log(idadeEpeso(78, 60)); //teste 2
console.log(idadeEpeso(16, 58)); //teste 3